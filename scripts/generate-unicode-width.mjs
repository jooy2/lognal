/**
 * Generates `src/core/text/unicode-width-data.ts` from the Unicode Character Database.
 *
 * The viewer lays text out on a grid of cells, so every code point needs a width: zero for
 * combining marks and format characters, two for East Asian wide and fullwidth characters,
 * and one for the rest. Ambiguous characters are listed separately because their width
 * depends on an option.
 *
 * Run it with `npm run generate:unicode` after changing `UNICODE_VERSION`, and commit the
 * result. The build never downloads anything.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const UNICODE_VERSION = '17.0.0';
const BASE_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd`;
const MAX_CODE_POINT = 0x10ffff;
const OUTPUT = join(
	dirname(fileURLToPath(import.meta.url)),
	'..',
	'src',
	'core',
	'text',
	'unicode-width-data.ts'
);

const WIDTH_NARROW = 0;
const WIDTH_WIDE = 1;
const WIDTH_AMBIGUOUS = 2;

const download = async (url) => {
	const response = await fetch(url);

	if (!response.ok) {
		throw new Error(`Could not download ${url}: ${response.status}`);
	}

	return response.text();
};

/** Calls `onRange` for every `start..end ; value` line, including `@missing` defaults. */
const forEachRange = (text, onRange) => {
	const defaults = [];
	const explicit = [];

	for (const rawLine of text.split('\n')) {
		const missing = rawLine.match(/^#\s*@missing:\s*([0-9A-F]+)\.\.([0-9A-F]+)\s*;\s*(\w+)/);

		if (missing) {
			defaults.push([parseInt(missing[1], 16), parseInt(missing[2], 16), missing[3]]);
			continue;
		}

		const line = rawLine.split('#')[0].trim();

		if (!line) {
			continue;
		}

		const [range, value] = line.split(';').map((part) => part.trim());
		const [start, end] = range.split('..').map((hex) => parseInt(hex, 16));

		explicit.push([start, end ?? start, value]);
	}

	for (const [start, end, value] of [...defaults, ...explicit]) {
		onRange(start, end, value);
	}
};

/** Collapses a per-code-point table into a flat `[start, end, start, end, ...]` list. */
const toRanges = (table, wanted) => {
	const ranges = [];
	let start = -1;

	for (let codePoint = 0; codePoint <= MAX_CODE_POINT + 1; codePoint++) {
		const matches = codePoint <= MAX_CODE_POINT && wanted(table[codePoint], codePoint);

		if (matches && start < 0) {
			start = codePoint;
		} else if (!matches && start >= 0) {
			ranges.push(start, codePoint - 1);
			start = -1;
		}
	}

	return ranges;
};

const formatRanges = (name, description, ranges) => {
	const lines = [];

	for (let index = 0; index < ranges.length; index += 8) {
		const chunk = ranges
			.slice(index, index + 8)
			.map((value) => `0x${value.toString(16)}`)
			.join(', ');

		lines.push(`\t${chunk}`);
	}

	return `/** ${description} */\nexport const ${name}: readonly number[] = [\n${lines.join(',\n')}\n];\n`;
};

const main = async () => {
	const [eastAsianWidth, generalCategory, license] = await Promise.all([
		download(`${BASE_URL}/EastAsianWidth.txt`),
		download(`${BASE_URL}/extracted/DerivedGeneralCategory.txt`),
		download('https://www.unicode.org/license.txt')
	]);

	const widths = new Uint8Array(MAX_CODE_POINT + 1);
	const zeroWidth = new Uint8Array(MAX_CODE_POINT + 1);

	forEachRange(eastAsianWidth, (start, end, value) => {
		const width =
			value === 'W' || value === 'F' ? WIDTH_WIDE : value === 'A' ? WIDTH_AMBIGUOUS : WIDTH_NARROW;

		widths.fill(width, start, end + 1);
	});

	forEachRange(generalCategory, (start, end, value) => {
		if (value === 'Mn' || value === 'Me' || value === 'Cf') {
			zeroWidth.fill(1, start, end + 1);
		}
	});

	// Hangul medial vowels and final consonants join the leading consonant before them into
	// one syllable, so they take no cell of their own.
	zeroWidth.fill(1, 0x1160, 0x11ff + 1);
	zeroWidth.fill(1, 0xd7b0, 0xd7ff + 1);

	const wide = toRanges(
		widths,
		(width, codePoint) => width === WIDTH_WIDE && !zeroWidth[codePoint]
	);
	const ambiguous = toRanges(
		widths,
		(width, codePoint) => width === WIDTH_AMBIGUOUS && !zeroWidth[codePoint]
	);
	const zero = toRanges(zeroWidth, (value) => value === 1);

	const licenseComment = license
		.trim()
		.split('\n')
		.map((line) => (line ? ` * ${line}` : ' *'))
		.join('\n');

	const output = [
		'/**',
		` * Character width data generated from the Unicode Character Database ${UNICODE_VERSION}`,
		' * (EastAsianWidth.txt and DerivedGeneralCategory.txt) by',
		' * `scripts/generate-unicode-width.mjs`. Do not edit this file by hand.',
		' *',
		' * Every list holds inclusive `[start, end]` pairs, flattened and sorted.',
		' *',
		licenseComment,
		' */',
		'',
		`export const UNICODE_VERSION = '${UNICODE_VERSION}';`,
		'',
		formatRanges(
			'WIDE_RANGES',
			'East Asian Wide and Fullwidth code points, drawn two cells wide.',
			wide
		),
		formatRanges(
			'AMBIGUOUS_RANGES',
			'East Asian Ambiguous code points, one or two cells wide depending on the option.',
			ambiguous
		),
		formatRanges(
			'ZERO_WIDTH_RANGES',
			'Combining marks, format characters and Hangul jamo that attach to the previous character.',
			zero
		)
	].join('\n');

	writeFileSync(OUTPUT, output);
	console.log(
		`Wrote ${OUTPUT}: ${wide.length / 2} wide, ${ambiguous.length / 2} ambiguous, ${zero.length / 2} zero-width ranges.`
	);
};

await main();
