/** Replaces each `{name}` in a message with its value. A placeholder without a value stays. */
export const formatMessage = (template: string, values: MessageValues = {}): string => {
	return template.replace(/\{([\w-]+)\}/g, (placeholder, name: string) => {
		return name in values ? String(values[name]) : placeholder;
	});
};
